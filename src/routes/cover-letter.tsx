import { createFileRoute } from "@tanstack/react-router";
import { useState, useEffect } from "react";
import { Sparkles, Copy, Check, Wand2, Shield, FileText, ChevronDown } from "lucide-react";
import { Card } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Textarea } from "@/components/ui/textarea";
import { Label } from "@/components/ui/label";
import { Alert, AlertDescription } from "@/components/ui/alert";
import { Navbar } from "@/components/Navbar";
import { Footer } from "@/components/Footer";
import {
  fetchJobOptions,
  generateCoverLetter,
  type JobOption,
  type CoverLetterData,
} from "@/lib/cover-letter";
import { ApiError, parseApiErrorMessage } from "@/lib/api";

export const Route = createFileRoute("/cover-letter")({
  head: () => ({
    meta: [
      { title: "AI Cover Letter - Jobyn AI" },
      {
        name: "description",
        content:
          "Generate a tailored cover letter in seconds. Jobyn AI matches your CV to the job description and writes application-ready copy.",
      },
      { property: "og:title", content: "AI Cover Letter - Jobyn AI" },
      {
        property: "og:description",
        content:
          "Tailored, application-ready cover letters generated by AI from your CV.",
      },
      { property: "og:type", content: "website" },
      { name: "twitter:card", content: "summary_large_image" },
    ],
  }),
  component: CoverLetterPage,
});

function CoverLetterPage() {
  const [jobs, setJobs] = useState<JobOption[]>([]);
  const [selectedJobId, setSelectedJobId] = useState("");
  const [additionalContext, setAdditionalContext] = useState("");
  const [result, setResult] = useState<CoverLetterData | null>(null);
  const [generating, setGenerating] = useState(false);
  const [loadingJobs, setLoadingJobs] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [copied, setCopied] = useState(false);

  // Load available jobs for the selector on mount
  useEffect(() => {
    fetchJobOptions()
      .then(setJobs)
      .catch(() => setJobs([]))
      .finally(() => setLoadingJobs(false));
  }, []);

  const selectedJob = jobs.find((j) => j.id === selectedJobId) ?? null;

  const generate = async () => {
    if (!selectedJobId) {
      setError("Please select a job first.");
      return;
    }
    setGenerating(true);
    setError(null);
    setResult(null);
    try {
      const data = await generateCoverLetter(selectedJobId, additionalContext);
      setResult(data);
    } catch (err) {
      const msg =
        err instanceof ApiError
          ? parseApiErrorMessage(err.detail, err.status)
          : "Cover letter generation failed. Please try again.";
      setError(msg);
    } finally {
      setGenerating(false);
    }
  };

  const copy = async () => {
    if (!result?.cover_letter) return;
    await navigator.clipboard.writeText(result.cover_letter);
    setCopied(true);
    setTimeout(() => setCopied(false), 1600);
  };

  return (
    <div className="flex min-h-screen flex-col bg-background">
      <Navbar />
      <main className="flex-1">
        <section className="border-b border-border/60 bg-gradient-to-b from-primary/[0.04] to-background">
          <div className="mx-auto max-w-6xl px-4 py-12 sm:px-6 sm:py-16 lg:px-8">
            <div className="flex items-center gap-2 text-sm font-medium text-primary">
              <Sparkles className="h-4 w-4" /> AI Cover Letter
            </div>
            <h1 className="mt-3 text-3xl font-bold tracking-tight text-foreground sm:text-4xl lg:text-5xl">
              Application-ready in one click
            </h1>
            <p className="mt-3 max-w-2xl text-lg text-muted-foreground">
              Select a matched job and Jobyn AI writes a personalised cover letter from your CV.
            </p>
          </div>
        </section>

        <section className="mx-auto grid max-w-6xl gap-6 px-4 py-10 sm:px-6 sm:py-14 lg:grid-cols-5 lg:gap-8 lg:px-8">
          {/* Left panel: inputs */}
          <Card className="p-6 lg:col-span-2">
            <h2 className="flex items-center gap-2 text-sm font-semibold uppercase tracking-wide text-foreground">
              <Wand2 className="h-4 w-4 text-primary" /> Job details
            </h2>

            {error && (
              <Alert variant="destructive" className="mt-4">
                <AlertDescription>{error}</AlertDescription>
              </Alert>
            )}

            <div className="mt-5 space-y-4">
              {/* Job selector */}
              <div>
                <Label htmlFor="job-select">Select a job</Label>
                <div className="relative mt-1.5">
                  <select
                    id="job-select"
                    value={selectedJobId}
                    onChange={(e) => setSelectedJobId(e.target.value)}
                    disabled={loadingJobs}
                    className="w-full appearance-none rounded-md border border-input bg-background px-3 py-2 pr-8 text-sm text-foreground focus:outline-none focus:ring-2 focus:ring-ring disabled:opacity-50"
                  >
                    <option value="">
                      {loadingJobs
                        ? "Loading jobs..."
                        : jobs.length === 0
                          ? "No jobs available — seed the database first"
                          : "-- select a job --"}
                    </option>
                    {jobs.map((j) => (
                      <option key={j.id} value={j.id}>
                        {j.title} @ {j.company}
                        {j.location ? ` · ${j.location}` : ""}
                      </option>
                    ))}
                  </select>
                  <ChevronDown className="pointer-events-none absolute right-2 top-1/2 h-4 w-4 -translate-y-1/2 text-muted-foreground" />
                </div>
                {selectedJob && (
                  <p className="mt-1 text-xs text-muted-foreground">
                    {selectedJob.title} at {selectedJob.company}
                  </p>
                )}
              </div>

              {/* Optional additional context */}
              <div>
                <Label htmlFor="context">
                  Additional context{" "}
                  <span className="font-normal text-muted-foreground">(optional)</span>
                </Label>
                <Textarea
                  id="context"
                  value={additionalContext}
                  onChange={(e) => setAdditionalContext(e.target.value)}
                  placeholder="Any extra context you want the AI to use — e.g. a recent project, specific motivation for this company, or skills not on your CV."
                  className="mt-1.5 min-h-32"
                  maxLength={2000}
                />
                {additionalContext.length > 0 && (
                  <p className="mt-1 text-right text-xs text-muted-foreground">
                    {additionalContext.length}/2000
                  </p>
                )}
              </div>

              <Button
                onClick={generate}
                disabled={generating || !selectedJobId}
                className="w-full"
                size="lg"
              >
                {generating ? (
                  <>
                    <Sparkles className="mr-2 h-4 w-4 animate-pulse" /> Generating...
                  </>
                ) : (
                  <>
                    <Sparkles className="mr-2 h-4 w-4" /> Generate cover letter
                  </>
                )}
              </Button>
            </div>
          </Card>

          {/* Right panel: output */}
          <Card className="p-6 lg:col-span-3">
            <div className="flex items-center justify-between">
              <h2 className="flex items-center gap-2 text-sm font-semibold uppercase tracking-wide text-foreground">
                <FileText className="h-4 w-4 text-primary" /> Preview
              </h2>
              {result?.cover_letter && (
                <Button variant="outline" size="sm" onClick={copy}>
                  {copied ? (
                    <>
                      <Check className="mr-2 h-4 w-4" /> Copied
                    </>
                  ) : (
                    <>
                      <Copy className="mr-2 h-4 w-4" /> Copy
                    </>
                  )}
                </Button>
              )}
            </div>

            <div className="mt-5 rounded-xl border border-border/70 bg-gradient-to-br from-background to-primary/[0.02] p-6">
              {!result && !generating && (
                <p className="text-sm text-muted-foreground">
                  Select a job and click Generate to create your personalised cover letter.
                </p>
              )}
              {generating && (
                <p className="animate-pulse text-sm text-muted-foreground">
                  <Sparkles className="mr-1 inline h-4 w-4" />
                  Generating your cover letter...
                </p>
              )}
              {result?.cover_letter && !generating && (
                <pre className="whitespace-pre-wrap font-sans text-sm leading-relaxed text-foreground">
                  {result.cover_letter}
                </pre>
              )}
            </div>

            {/* Key selling points */}
            {result && result.key_selling_points.length > 0 && (
              <div className="mt-5">
                <p className="text-xs font-semibold uppercase tracking-wide text-muted-foreground">
                  Key selling points
                </p>
                <ul className="mt-2 space-y-1">
                  {result.key_selling_points.map((p, i) => (
                    <li key={i} className="flex items-start gap-2 text-sm text-foreground">
                      <span className="mt-1 h-1.5 w-1.5 shrink-0 rounded-full bg-primary" />
                      {p}
                    </li>
                  ))}
                </ul>
              </div>
            )}

            {/* Application tips */}
            {result && result.application_tips.length > 0 && (
              <div className="mt-5">
                <p className="text-xs font-semibold uppercase tracking-wide text-muted-foreground">
                  Application tips
                </p>
                <ul className="mt-2 space-y-1">
                  {result.application_tips.map((t, i) => (
                    <li key={i} className="text-sm text-muted-foreground">
                      {i + 1}. {t}
                    </li>
                  ))}
                </ul>
              </div>
            )}

            <div className="mt-4 flex items-start gap-2 text-xs text-muted-foreground">
              <Shield className="mt-0.5 h-3.5 w-3.5 shrink-0 text-primary" />
              AI-generated. Please review before sending — a quick human pass catches nuance the model misses.
            </div>
          </Card>
        </section>
      </main>
      <Footer />
    </div>
  );
}
