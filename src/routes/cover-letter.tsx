import { createFileRoute } from "@tanstack/react-router";
import { useState } from "react";
import { Sparkles, Copy, Check, Wand2, Shield, FileText } from "lucide-react";
import { Card } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Textarea } from "@/components/ui/textarea";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Navbar } from "@/components/Navbar";
import { Footer } from "@/components/Footer";

export const Route = createFileRoute("/cover-letter")({
  head: () => ({
    meta: [
      { title: "AI Cover Letter — Jobyn AI" },
      { name: "description", content: "Generate a tailored cover letter in seconds. Jobyn AI matches your CV to the job description and writes application-ready copy." },
      { property: "og:title", content: "AI Cover Letter — Jobyn AI" },
      { property: "og:description", content: "Tailored, application-ready cover letters generated by AI from your CV." },
      { property: "og:type", content: "website" },
      { name: "twitter:card", content: "summary_large_image" },
    ],
  }),
  component: CoverLetterPage,
});

const SAMPLE_LETTER = `Dear Hiring Team,

I'm writing to express my interest in the Staff Frontend Engineer role at Linear. With seven years of experience shipping performant, well-designed web products in React and TypeScript, I'm drawn to Linear's obsession with craft, speed, and thoughtful defaults.

At Northwind Labs I led the migration from CRA to Next.js App Router, reducing time-to-interactive by 43% and unblocking a design-system rollout used by six product teams. Before that, at Cobalt Health, I owned a patient-facing dashboard used by 120k monthly users and introduced end-to-end testing that cut regressions by 60%.

What excites me about Linear is the combination of a small, senior team and a product with clear opinions. I'd love to contribute to the design system, editor performance, and the parts of the product where interaction feel makes or breaks the experience.

I'd welcome the chance to talk about how I can help.

Best,
Alex Morgan`;

function CoverLetterPage() {
  const [role, setRole] = useState("Staff Frontend Engineer");
  const [company, setCompany] = useState("Linear");
  const [jd, setJd] = useState("");
  const [letter, setLetter] = useState(SAMPLE_LETTER);
  const [generating, setGenerating] = useState(false);
  const [copied, setCopied] = useState(false);

  const generate = () => {
    setGenerating(true);
    setTimeout(() => {
      setLetter(SAMPLE_LETTER.replace(/Linear/g, company).replace(/Staff Frontend Engineer/g, role));
      setGenerating(false);
    }, 900);
  };

  const copy = async () => {
    await navigator.clipboard.writeText(letter);
    setCopied(true);
    setTimeout(() => setCopied(false), 1600);
  };

  return (
    <div className="flex min-h-screen flex-col bg-background">
      <Navbar />
      <main className="flex-1">
        <section className="border-b border-border/60 bg-gradient-to-b from-primary/[0.04] to-background">
          <div className="mx-auto max-w-6xl px-4 py-12 sm:px-6 sm:py-16 lg:px-8">
            <div className="flex items-center gap-2 text-sm font-medium text-primary">
              <Sparkles className="h-4 w-4" /> AI Cover Letter
            </div>
            <h1 className="mt-3 text-3xl font-bold tracking-tight text-foreground sm:text-4xl lg:text-5xl">
              Application-ready in one click
            </h1>
            <p className="mt-3 max-w-2xl text-lg text-muted-foreground">
              Paste a job description — Jobyn AI writes a personalized cover
              letter that matches your CV and the role.
            </p>
          </div>
        </section>

        <section className="mx-auto grid max-w-6xl gap-6 px-4 py-10 sm:px-6 sm:py-14 lg:grid-cols-5 lg:gap-8 lg:px-8">
          <Card className="p-6 lg:col-span-2">
            <h2 className="flex items-center gap-2 text-sm font-semibold uppercase tracking-wide text-foreground">
              <Wand2 className="h-4 w-4 text-primary" /> Job details
            </h2>
            <div className="mt-5 space-y-4">
              <div>
                <Label htmlFor="role">Role</Label>
                <Input id="role" value={role} onChange={(e) => setRole(e.target.value)} className="mt-1.5" />
              </div>
              <div>
                <Label htmlFor="company">Company</Label>
                <Input id="company" value={company} onChange={(e) => setCompany(e.target.value)} className="mt-1.5" />
              </div>
              <div>
                <Label htmlFor="jd">Job description (optional)</Label>
                <Textarea
                  id="jd"
                  value={jd}
                  onChange={(e) => setJd(e.target.value)}
                  placeholder="Paste the JD here — the more detail, the better the letter."
                  className="mt-1.5 min-h-40"
                />
              </div>
              <Button onClick={generate} disabled={generating} className="w-full" size="lg">
                {generating ? (
                  <>
                    <Sparkles className="mr-2 h-4 w-4 animate-pulse" /> Generating…
                  </>
                ) : (
                  <>
                    <Sparkles className="mr-2 h-4 w-4" /> Generate cover letter
                  </>
                )}
              </Button>
            </div>
          </Card>

          <Card className="p-6 lg:col-span-3">
            <div className="flex items-center justify-between">
              <h2 className="flex items-center gap-2 text-sm font-semibold uppercase tracking-wide text-foreground">
                <FileText className="h-4 w-4 text-primary" /> Preview
              </h2>
              <Button variant="outline" size="sm" onClick={copy}>
                {copied ? (
                  <>
                    <Check className="mr-2 h-4 w-4" /> Copied
                  </>
                ) : (
                  <>
                    <Copy className="mr-2 h-4 w-4" /> Copy
                  </>
                )}
              </Button>
            </div>
            <div className="mt-5 rounded-xl border border-border/70 bg-gradient-to-br from-background to-primary/[0.02] p-6">
              <pre className="whitespace-pre-wrap font-sans text-sm leading-relaxed text-foreground">
                {letter}
              </pre>
            </div>
            <div className="mt-4 flex items-start gap-2 text-xs text-muted-foreground">
              <Shield className="mt-0.5 h-3.5 w-3.5 shrink-0 text-primary" />
              AI-generated. Please review before sending — a quick human pass
              catches nuance the model misses.
            </div>
          </Card>
        </section>
      </main>
      <Footer />
    </div>
  );
}
